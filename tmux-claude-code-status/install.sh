#!/bin/sh
# Install the Claude Code -> tmux agent status integration.
#
#   curl -fsSL https://raw.githubusercontent.com/shortcuts/dotfiles/main/tmux-claude-code-status/install.sh | sh
#
# Non-interactive run (no tty) answers yes to every prompt.
# Needs: curl, jq. tmux is only needed to use the result.
set -eu

# RAW is overridable so `make tmux-status` can install the hook from a checkout.
RAW="${RAW:-https://raw.githubusercontent.com/shortcuts/dotfiles/main/.claude/hooks/tmux-agent-notify.sh}"
HOOK_DIR="$HOME/.claude/hooks"
HOOK="$HOOK_DIR/tmux-agent-notify.sh"
SETTINGS="$HOME/.claude/settings.json"
TMUX_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/tmux"
FRAGMENT="$TMUX_DIR/tmux-claude-code-status.conf"

DOT='#{?@agent_win_state,#{?#{==:#{@agent_win_state},stuck},#[fg=red],#{?#{==:#{@agent_win_state},working},#[fg=orange],#[fg=green]}}● #[default],}'

die() { printf 'error: %s\n' "$1" >&2; exit 1; }

ask() {
    # -r /dev/tty lies when the device exists but cannot be opened
    { : </dev/tty; } 2>/dev/null || { printf 'y\n'; return; }
    printf '%s [Y/n] ' "$1" >/dev/tty
    read -r reply </dev/tty || reply=y
    case "${reply:-y}" in [Nn]*) printf 'n\n' ;; *) printf 'y\n' ;; esac
}

command -v curl >/dev/null || die "curl is required"
command -v jq >/dev/null || die "jq is required"

want_window=$(ask "Colored agent dot on the tmux window (status bar)?")
want_tree=$(ask "Agent state in the session tree (rebinds <prefix> s)?")
want_notify=$(ask "Desktop notification when Claude stops or needs input?")

# 1. hook script
mkdir -p "$HOOK_DIR"
curl -fsSL "$RAW" -o "$HOOK.tmp" || die "cannot download $RAW"
mv "$HOOK.tmp" "$HOOK"
chmod +x "$HOOK"
if [ "$want_notify" = n ]; then
    printf 'NOTIFY=0\n' >"$HOOK_DIR/tmux-agent-notify.conf"
else
    rm -f "$HOOK_DIR/tmux-agent-notify.conf"
fi

# 2. hook wiring
# PreToolUse repaints working as soon as you approve a permission prompt,
# instead of leaving the pane red until the turn ends.
CMD='sh ~/.claude/hooks/tmux-agent-notify.sh'
EVENTS='SessionStart:start UserPromptSubmit:working PreToolUse:working PermissionRequest:stuck Notification:notification Stop:stop SessionEnd:end'

mkdir -p "$(dirname "$SETTINGS")"
[ -s "$SETTINGS" ] || printf '{}\n' >"$SETTINGS"
jq --arg h "$CMD" --arg events "$EVENTS" '
  def strip: (. // [])
    | map(.hooks |= map(select((.command // "") | test("tmux-agent-notify") | not)))
    | map(select((.hooks | length) > 0));
  reduce ($events | split(" ") | .[] | split(":")) as [$event, $arg] (.;
    .hooks = (.hooks // {})
    | .hooks[$event] = ((.hooks[$event] | strip)
        + [{hooks: [{type: "command", command: "\($h) \($arg)"}]}]))
' "$SETTINGS" >"$SETTINGS.tmp" || die "cannot patch $SETTINGS"
mv "$SETTINGS.tmp" "$SETTINGS"

# 3. tmux fragment
# Formats are read from the running server so an existing custom format
# survives; the sed drops a dot appended by an earlier run.
base_fmt=$(tmux show-options -gv window-status-format 2>/dev/null || true)
base_cur=$(tmux show-options -gv window-status-current-format 2>/dev/null || true)
[ -n "$base_fmt" ] || base_fmt='#I:#W#F '
[ -n "$base_cur" ] || base_cur='#I:#W#F '
base_fmt=$(printf '%s' "$base_fmt" | sed 's/#{?@agent_win_state,.*$//')
base_cur=$(printf '%s' "$base_cur" | sed 's/#{?@agent_win_state,.*$//')

mkdir -p "$TMUX_DIR"
{
    printf '# Generated by tmux-claude-code-status. Re-run the installer to regenerate.\n'
    printf '# States: working (orange), stuck (red), idle (green).\n'
    if [ "$want_window" = y ]; then
        printf 'set -gw window-status-format "%s%s"\n' "$base_fmt" "$DOT"
        printf 'set -gw window-status-current-format "%s%s"\n' "$base_cur" "$DOT"
    fi
    if [ "$want_tree" = y ]; then
        printf "bind-key s choose-tree -Zs -F '#{?session_format,#{session_windows} windows#{?@agent_state, #{?#{==:#{@agent_state},stuck},#[fg=red],#{?#{==:#{@agent_state},working},#[fg=orange],#[fg=green]}}● #{@agent_state}#[default],},#{?window_format,#{window_name},}}'\n"
    fi
} >"$FRAGMENT"

# 4. source line
# ~-relative and -q so the same tmux.conf works on another machine, whose
# $HOME differs and where the generated fragment may not exist yet.
src_line="source-file -q $FRAGMENT"
case "$FRAGMENT" in "$HOME"/*) src_line="source-file -q ~/${FRAGMENT#"$HOME"/}" ;; esac
conf=""
for c in "$TMUX_DIR/tmux.conf" "$HOME/.tmux.conf"; do
    [ -f "$c" ] && { conf="$c"; break; }
done
if [ -z "$conf" ]; then
    conf="$TMUX_DIR/tmux.conf"
    printf '%s\n' "$src_line" >"$conf"
    printf 'created %s\n' "$conf"
elif grep -qF "tmux-claude-code-status.conf" "$conf"; then
    :
elif [ "$(ask "Add '$src_line' to $conf?")" = y ]; then
    printf '\n%s\n' "$src_line" >>"$conf"
else
    printf '\nAdd this line to your tmux.conf yourself:\n    %s\n' "$src_line"
fi

# A broken line elsewhere in the user's tmux.conf must not fail the install.
[ -n "${TMUX:-}" ] && { tmux source-file "$conf" >/dev/null 2>&1 || true; }

printf '\nDone. Restart Claude Code to load the hooks.\n'
printf 'Hook:     %s\n' "$HOOK"
printf 'tmux:     %s\n' "$FRAGMENT"
printf 'Settings: %s\n' "$SETTINGS"
